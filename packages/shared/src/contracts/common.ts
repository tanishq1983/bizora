import { z } from 'zod';

/** A single meaningful sentence. Kept generous so the model is never punished for length. */
export const text = (max = 2000) => z.string().trim().min(1).max(max);

/** A short phrase, used for bullets, tags and list items. */
export const phrase = (max = 300) => z.string().trim().min(1).max(max);

/** A bounded list of bullets. */
export const bullets = (min = 1, max = 8) => z.array(phrase()).min(min).max(max);

/** An integer score on a fixed scale. */
export const score = (max: number) => z.number().int().min(0).max(max);

/**
 * A human-readable currency or cost range. Deliberately a string rather than a
 * number: a figure like "₹8L – ₹18L for a credible first version with real
 * matching" carries the qualifier that makes the estimate honest, and a number
 * would strip it. The cap is generous because the live model tends to annotate
 * these, and a too-tight cap would spend a repair round-trip on length alone.
 */
export const costRange = z.string().trim().min(1).max(600);

/** Fixed, product-owned copy that must never be generated by the model. */
export const ESTIMATE_DISCLAIMER =
  'AI-generated estimate. Figures are directional projections based on the idea description, not verified market data. Validate with primary research before making funding decisions.';

export const AI_METHOD_NOTE =
  'Scored by the Bizora Builder Agent against a fixed rubric. Treat as a directional signal, not a verified verdict.';